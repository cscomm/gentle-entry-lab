// Generates supabase/functions/product-finder/catalog.ts — a compact product
// summary the AI product finder uses as reference. Built from the MCP catalog
// (src/lib/mcp/catalog.generated.ts, itself generated from src/data/products.ts).
// Run after scripts/generate-mcp-catalog.ts (see package.json "build").
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { productCatalog } from "../src/lib/mcp/catalog.generated";

const clip = (s: string | undefined, n: number) => {
  const t = (s ?? "").replace(/\s+/g, " ").trim();
  return t.length > n ? t.slice(0, n) + "…" : t;
};

const seen = new Set<string>();
const items = productCatalog
  .filter((p) => {
    if (seen.has(p.slug)) return false;
    seen.add(p.slug);
    return true;
  })
  .map((p) => ({
    slug: p.slug,
    name: p.name,
    en: p.enName,
    group: p.isCategoryIndex ? "CATEGORY" : p.parentSlug ?? p.category ?? "",
    tag: clip(p.tagline, 90),
    desc: clip(p.description, p.isCategoryIndex ? 180 : 120),
    apps: (p.applications ?? []).slice(0, 5).map((a) => clip(a, 30)),
    specs: (p.specs ?? []).slice(0, 4).map((s) => `${clip(s.label, 20)}: ${clip(s.value, 40)}`),
    models: p.isCategoryIndex ? undefined : (p.subModels ?? []).slice(0, 8).map((m) => m.code),
  }));

const out = resolve("supabase/functions/product-finder/catalog.ts");
mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  `// AUTO-GENERATED by scripts/generate-finder-catalog.ts — do not edit by hand.\n` +
    `export type FinderItem = { slug: string; name: string; en: string; group: string; tag: string; desc: string; apps: string[]; specs: string[]; models?: string[] };\n` +
    `export const finderCatalog: FinderItem[] = ${JSON.stringify(items)};\n`,
  "utf8",
);
console.log(`Wrote ${out} (${items.length} products)`);
